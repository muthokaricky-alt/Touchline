// Writes the website's service worker (offline support) into an exported build.
// Usage: node scripts/build-sw.mjs dist   (run by `npm run build:web` after `expo export`)
//
// The worker pre-caches EVERY file of the build on the first visit, so the
// whole game then works offline (it's single-player and saves in the browser).
// Its cache is named after a hash of all file contents: a new deploy has a
// new name, so returning players get the new version and the old cache is
// deleted. Pages are served from the cache too; a page that wasn't
// pre-rendered (another club's player profile) gets index.html, which loads
// the app, and the app shows the right screen.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const [outDir] = process.argv.slice(2);
if (!outDir) throw new Error('Usage: node scripts/build-sw.mjs <export folder>');

/** Files not worth caching for offline play. */
const SKIP = new Set(['sw.js', '_headers', '_redirects', '_sitemap.html']);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = walk(outDir)
  .map((path) => ({ path, url: '/' + relative(outDir, path).split(sep).join('/') }))
  .filter(({ url }) => !SKIP.has(url.slice(1)))
  .sort((a, b) => a.url.localeCompare(b.url));

/** Bump when the worker's caching logic changes, so it starts with a fresh cache. */
const FORMAT = 3;
const hash = createHash('sha256').update(`format ${FORMAT}`);
for (const { url, path } of files) hash.update(url).update(readFileSync(path));
const version = hash.digest('hex').slice(0, 12);

/**
 * The address a file is requested at. Pages by their clean address
 * ("/squad", "/" for index.html): hosts like Cloudflare redirect
 * "/squad.html" to "/squad", and Chrome won't serve a redirected response
 * for a page load. Each path segment percent-encoded the way hosts expect
 * ("@" → "%40", "+" → "%2B"), so nothing is redirected.
 */
function requestUrl(url) {
  const clean = url.endsWith('/index.html') ? url.slice(0, -'index.html'.length) : url.endsWith('.html') ? url.slice(0, -'.html'.length) : url;
  return clean.split('/').map(encodeURIComponent).join('/');
}
// Not needed offline: the router's own not-found page.
const urls = files.filter(({ url }) => !url.includes('+not-found')).map(({ url }) => requestUrl(url));
/** Must be cached for the game to work offline: the start page and the app's code. */
const essential = urls.filter((u) => u === '/' || u.startsWith('/_expo/static/js/'));

const worker = `// Generated by scripts/build-sw.mjs: do not edit.
const CACHE = 'touchline-${version}';
const FILES = ${JSON.stringify(urls)};
const ESSENTIAL = new Set(${JSON.stringify(essential)});

/** Same path, each segment percent-encoded (how the files are cached). */
const canonical = (path) => path.split('/').map((s) => encodeURIComponent(decodeURIComponent(s))).join('/');

/** Give up on one download after this long (it's retried). */
const TIMEOUT_MS = 30000;

/**
 * Downloads a file COMPLETELY into memory (with a time limit) before it goes
 * into the cache. Handing a still-downloading response to the cache let one
 * stalled download hold up every other write: on the live site the cache
 * sometimes stayed empty for minutes. The copy also has no "redirected" mark
 * (Chrome refuses redirected responses for page loads).
 */
async function download(url) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
  try {
    const response = await fetch(url, { cache: 'reload', signal: controller.signal });
    if (!response.ok) return null;
    const body = await response.arrayBuffer();
    return new Response(body, { status: response.status, statusText: response.statusText, headers: response.headers });
  } finally {
    clearTimeout(timer);
  }
}

/** Downloads one file (two retries) into the cache; true if it worked. */
async function store(cache, url) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const response = await download(url);
      if (response) {
        await cache.put(url, response);
        return true;
      }
    } catch {
      // Network blip or timeout: try again.
    }
  }
  return false;
}

// Install: download everything, six at a time. Only the essentials must succeed (an icon that
// fails doesn't stop offline play; the next version's install tries again).
self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      const queue = [...FILES];
      const failed = [];
      await Promise.all(
        Array.from({ length: 6 }, async () => {
          for (let url = queue.shift(); url !== undefined; url = queue.shift()) {
            if (!(await store(cache, url))) failed.push(url);
          }
        }),
      );
      if (failed.some((url) => ESSENTIAL.has(url))) throw new Error('Offline copy incomplete: ' + failed.join(', '));
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('touchline-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  const path = canonical(url.pathname);

  if (request.mode === 'navigate') {
    event.respondWith(
      (async () => {
        const cache = await caches.open(CACHE);
        const clean = path.endsWith('.html') ? path.slice(0, -5) : path;
        for (const candidate of [clean, clean.endsWith('/index') ? clean.slice(0, -5) : clean + '/']) {
          const hit = await cache.match(candidate);
          if (hit) return hit;
        }
        // Not pre-rendered (e.g. another club's player profile): the app shell, which shows the
        // right screen. Also when the network is down or the host has no fallback (a 404).
        try {
          const response = await fetch(request);
          if (response.ok) return response;
          return (await cache.match('/')) ?? response;
        } catch {
          return (await cache.match('/')) ?? Response.error();
        }
      })(),
    );
    return;
  }

  event.respondWith(
    (async () => (await caches.match(request)) ?? (await caches.match(path)) ?? fetch(request))(),
  );
});
`;

writeFileSync(join(outDir, 'sw.js'), worker);
const bytes = files.reduce((sum, { path }) => sum + statSync(path).size, 0);
console.log(`sw.js: ${urls.length} files (${(bytes / 1024 / 1024).toFixed(1)} MB), ${essential.length} essential, cached as touchline-${version}`);
